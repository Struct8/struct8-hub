/**
 * Writes src/resources/index.ts from the folders that are actually there.
 *
 * Generated rather than discovered at runtime: runtime discovery needs a filesystem or a bundler
 * plugin, and Cloudflare Workers has neither. Static imports are also what lets a deployment drop
 * the resources its diagram does not use.
 */

import { readdirSync, writeFileSync, readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'src', 'resources');
const out = join(dir, 'index.ts');

const types = readdirSync(dir, { withFileTypes: true })
	.filter((e) => e.isDirectory())
	.map((e) => e.name)
	.sort();

const body = `// GENERATED by scripts/gen-registry.mjs — do not edit.
// Run \`npm run gen:registry\` after adding or removing a resource folder.
//
// Importing this module registers every resource. A deployment that only needs some of them
// should import those directly instead: \`import '@struct8/hub/r/aws_sqs_queue'\`.

${types.map((t) => `import './${t}/index.js';`).join('\n')}

/** Every resource type this build knows about, in registration order. */
export const BUNDLED: readonly string[] = ${JSON.stringify(types, null, 1).replace(/\n\s*/g, ' ').replace(/ \]$/, ' ]')};
`;

const previous = (() => {
	try {
		return readFileSync(out, 'utf8');
	} catch {
		return '';
	}
})();

if (previous === body) {
	console.log(`gen:registry — unchanged (${types.length} resources)`);
} else {
	writeFileSync(out, body);
	console.log(`gen:registry — wrote ${types.length} resources: ${types.join(', ')}`);
}
